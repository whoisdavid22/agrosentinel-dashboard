type Dict = typeof dict.es;
export type TKey = keyof Dict;

export function t<K extends TKey>(lang: Lang, key: K, ...args: Dict[K] extends (...a: infer A) => string ? A : []): string {
  const entry = dict[lang][key] ?? dict.es[key];
  if (typeof entry === 'function') {
    return (entry as (...a: unknown[]) => string)(...args);
  }
  return entry as string;
}

// Returns a translator bound to one language, so components can call tr('key', args) directly.
export function makeT(lang: Lang) {
  return function tr<K extends TKey>(key: K, ...args: Dict[K] extends (...a: infer A) => string ? A : []): string {
    return t(lang, key, ...args);
  };
}

// Humanizes machine-style identifiers Claude sometimes returns as "factor"
// names (e.g. "dias_sin_intervencion" -> "Días sin intervención").
export function humanize(text: string): string {
  if (!text) return text;
  const spaced = text.replace(/_/g, ' ').trim();
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}
